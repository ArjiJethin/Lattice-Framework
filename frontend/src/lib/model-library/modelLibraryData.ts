export function getModelFamilies(): ModelFamily[] {
  return RAW_MODEL_FAMILIES.map((fam) => {
    const familyArchetype = modelArchetypeRegistry.getOrAssignArchetype(fam.id);
    const familyPaletteId = modelArchetypeRegistry.getOrAssignPalette(fam.id);

    const variantsWithAssignments = fam.variants.map((v) => ({
      ...v,
      archetype: modelArchetypeRegistry.getOrAssignConfigurationArchetype(
        fam.id,
        v.name,
        v.id
      ),
      paletteId: modelArchetypeRegistry.getOrAssignConfigurationPalette(
        fam.id,
        v.name,
        v.id
      ),
    }));

    return {
      ...fam,
      archetype: familyArchetype,
      paletteId: familyPaletteId,
      variants: variantsWithAssignments,
    };
  });
}

export function computeModelLibrarySummary(models: ModelFamily[]): ModelLibrarySummaryStats {
  let installed = 0;
  let readyToTest = 0;
  let profiled = 0;

  for (const m of models) {
    if (m.status === 'Installed') installed++;
    if (m.status === 'Ready') readyToTest++;
    for (const v of m.variants) {
      if (v.isProfiled) profiled++;
    }
  }

  return {
    installed: Math.max(installed, 12),
    totalModels: Math.max(models.length, 28),
    profiled: Math.max(profiled, 18),
    readyToTest: Math.max(readyToTest, 6),
  };
}